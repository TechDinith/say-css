// scripts/gen-types.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(ROOT, "src", "utilities.css"), "utf8");

const names = new Set();
const re = /\.((?:\\.|[^.\s{])+)/g;
let m;
while ((m = re.exec(css)) !== null) {
  let name = m[1].replace(/\\(.)/g, "$1");
  if (name && !name.startsWith("@")) names.add(name);
}

const sorted = [...names].sort();
const union = sorted.map(n => JSON.stringify(n)).join(" | \n  ");
const dts = `// Auto-generated by scripts/gen-types.mjs — do not edit.
export type SayClass =
  ${union};

export interface SayProps {
  className?: SayClass | SayClass[] | string;
}
`;
mkdirSync(join(ROOT, "types"), { recursive: true });
writeFileSync(join(ROOT, "types", "index.d.ts"), dts);
writeFileSync(join(ROOT, "types", "classes.json"), JSON.stringify(sorted));
console.log("Extracted", sorted.length, "class names -> types/");
